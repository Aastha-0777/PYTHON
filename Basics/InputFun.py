# input() and type casting 

num = input('Enter a Number : ')
print('the value of num is :', num)
print('the type of num is :', type(num))

num1 = int(input('Enter the Value of Num1 : '))
print('the value of num1 is :', num1)
print('the type of num1 is :', type(num1))

num2 = float(input('Enter the value of Num2 : '))
print('the value of num2 is :', num2)
print('the type of num2 is :', type(num2))

name = input("enter the Name : ")
print('the value of name :', name)
print('the type of name :', type(name))

